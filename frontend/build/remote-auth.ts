import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import Ajv from 'ajv';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { createRequire } from 'node:module';

const schemaFile = new URL('../../test/contract-fixtures/agent-remote-auth/schemas.json', import.meta.url);
export const remoteAuthValidatorFile = new URL('../src/onboarding/remote-auth.validator.mjs', import.meta.url);
export const remoteAuthSchemaNames = ['consentView', 'consentApproveRequest', 'consentApproved', 'consentDecided', 'consentDenied', 'bootstrapCodeRequest', 'bootstrapCodeIssued'] as const;
export function generateRemoteAuthValidators() {
  const schema = JSON.parse(readFileSync(schemaFile, 'utf8'));
  const hash = createHash('sha256').update(JSON.stringify(schema)).digest('hex');
  const ajv = new Ajv({ strict: false, code: { source: true, esm: true } });
  addFormats(ajv); ajv.addSchema(schema);
  const require = createRequire(import.meta.url);
  // Inline Ajv's own runtime helpers at build time; the browser needs no require/eval.
  const runtime = 'const canonicalLength = ' + require('ajv/dist/runtime/ucs2length').default.toString() + ';\n'
    + 'const canonicalEqual = ' + require('ajv/dist/runtime/equal').default.toString() + ';\n';
  const generated = standaloneCode(ajv, Object.fromEntries(remoteAuthSchemaNames.map(name => [name, schema.$id + '#/definitions/' + name])))
    .replaceAll('require("ajv/dist/runtime/ucs2length").default', 'canonicalLength')
    .replaceAll('require("ajv/dist/runtime/equal").default', 'canonicalEqual');
  if (/\brequire\(/.test(generated)) throw new Error('Unexpected browser validator runtime dependency');
  return '// Generated by npm run build from canonical agent-remote-auth schemas.json. Do not edit.\n'
    + '// Canonical schema SHA256: ' + hash + '\n'
    + runtime + generated + '\n';
}
export function remoteAuthValidatorPlugin() {
  return { name: 'canonical-remote-auth-validators', buildStart() {
    const generated = generateRemoteAuthValidators();
    const previous = existsSync(remoteAuthValidatorFile) ? readFileSync(remoteAuthValidatorFile, 'utf8').replace(/\r\n/g, '\n') : '';
    if (previous !== generated) writeFileSync(remoteAuthValidatorFile, generated);
  } };
}
