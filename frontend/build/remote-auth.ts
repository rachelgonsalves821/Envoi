import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import Ajv from 'ajv';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { createRequire } from 'node:module';

const schemaFile = new URL('../../test/contract-fixtures/agent-remote-auth/schemas.json', import.meta.url);
export const remoteAuthValidatorFile = new URL('../src/onboarding/remote-auth.validator.mjs', import.meta.url);
export const remoteAuthSchemaNames = ['consentView', 'consentApproveRequest', 'consentApproved', 'consentDecided', 'consentDenied', 'bootstrapCodeRequest', 'bootstrapCodeIssued', 'savedSetup'] as const;

// agent-saved-setup v1 extends the existing closed consent shapes. Retain all
// of their validation and add the fields used by the wizard and consent page.
function addSavedSetupSchemas(definitions: Record<string, any>) {
  const ref = (name: string) => ({ $ref: '#/definitions/' + name });
  const closed = (properties: Record<string, unknown>) => ({
    type: 'object', additionalProperties: false, required: Object.keys(properties), properties
  });
  const date = definitions.consentView.properties.expiresAt;
  const setupId = { type: 'string', pattern: '^setup_[A-Za-z0-9_-]{1,80}$' };
  const preferences = {
    setupId,
    workspaceInboxId: { type: 'string', pattern: '^inbox_[A-Za-z0-9_-]{1,80}$' },
    workspaceName: { type: 'string', minLength: 1, maxLength: 80 },
    name: { type: 'string', minLength: 1, maxLength: 80 },
    localPart: ref('localPart'),
    address: { type: 'string', pattern: '^[a-z][a-z0-9.-]*@[a-z0-9.-]+$' },
    permissions: ref('savedSetupGrant'),
    expiresAt: date
  };
  definitions.savedSetupPermissions = {
    type: 'array', uniqueItems: true, maxItems: 4,
    items: { enum: ['receive_agent_messages', 'send_agent_messages', 'create_assets', 'execute_cases'] }
  };
  definitions.savedSetupGrant = {
    allOf: [ref('savedSetupPermissions'), { contains: { const: 'receive_agent_messages' } }]
  };
  definitions.consentSavedSetup = closed({
    ...preferences, notRequested: ref('savedSetupPermissions'), addressAvailable: { type: 'boolean' }
  });
  definitions.consentView.properties.savedSetup = ref('consentSavedSetup');
  definitions.consentView.allOf = [
    ...(definitions.consentView.allOf ?? []),
    { if: { required: ['savedSetup'] }, then: { not: { required: ['decision'] }, properties: { connectionRoute: { const: 'remote_mcp_oauth' } } } }
  ];
  definitions.consentApproveRequest.properties.savedSetupId = setupId;
  definitions.consentApproved.properties.savedSetup = closed({ setupId, linked: { type: 'boolean' } });

  const agent = { name: preferences.name, address: preferences.address };
  const setup = { ...preferences, runtime: { const: 'dots' }, createdAt: date };
  definitions.savedSetup = {
    oneOf: [
      closed({ ...setup, status: { enum: ['waiting', 'replaced'] } }),
      closed({ ...setup, status: { const: 'approved' }, agent: closed(agent) }),
      closed({
        ...setup, status: { const: 'connected' },
        agent: closed({ ...agent, id: { type: 'string', pattern: '^agent_[A-Za-z0-9_-]{1,80}$' }, lastSeenAt: { anyOf: [date, { type: 'null' }] } }),
        effectivePermissions: ref('savedSetupGrant')
      }),
      closed({ ...setup, status: { const: 'expired' }, reason: { enum: ['not_used', 'approval_lapsed'] } })
    ]
  };
}

export function generateRemoteAuthValidators() {
  const schema = JSON.parse(readFileSync(schemaFile, 'utf8'));
  addSavedSetupSchemas(schema.definitions);
  const hash = createHash('sha256').update(JSON.stringify(schema)).digest('hex');
  const ajv = new Ajv({ strict: false, code: { source: true, esm: true } });
  addFormats(ajv); ajv.addSchema(schema);
  const require = createRequire(import.meta.url);
  // Inline Ajv's own runtime helpers at build time; the browser needs no require/eval.
  const runtime = 'const canonicalLength = ' + require('ajv/dist/runtime/ucs2length').default.toString() + ';\n'
    + 'const canonicalEqual = ' + require('ajv/dist/runtime/equal').default.toString() + ';\n';
  const generated = standaloneCode(ajv, Object.fromEntries(remoteAuthSchemaNames.map(name => [name, schema.$id + '#/definitions/' + name])))
    .replaceAll('require("ajv/dist/runtime/ucs2length").default', 'canonicalLength')
    .replaceAll('require("ajv/dist/runtime/equal").default', 'canonicalEqual');
  if (/\brequire\(/.test(generated)) throw new Error('Unexpected browser validator runtime dependency');
  return '// Generated by npm run build from agent-remote-auth schemas with agent-saved-setup v1 extensions. Do not edit.\n'
    + '// Generated schema SHA256: ' + hash + '\n'
    + runtime + generated + '\n';
}
export function remoteAuthValidatorPlugin() {
  return { name: 'canonical-remote-auth-validators', buildStart() {
    const generated = generateRemoteAuthValidators();
    const previous = existsSync(remoteAuthValidatorFile) ? readFileSync(remoteAuthValidatorFile, 'utf8').replace(/\r\n/g, '\n') : '';
    if (previous !== generated) writeFileSync(remoteAuthValidatorFile, generated);
  } };
}
