import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import Ajv from 'ajv';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';

const schemaFile = new URL('../../test/contract-fixtures/agent-registration/schemas.json', import.meta.url);
export const validatorFile = new URL('../src/onboarding/route-availability.validator.mjs', import.meta.url);
export const routeEnumsFile = new URL('../src/onboarding/route-availability-enums.ts', import.meta.url);

/** Emit only the two public route enums, never the stored-record schema. */
export function generateRouteAvailabilityEnums() {
  const schema = JSON.parse(readFileSync(schemaFile, 'utf8'));
  const routes = schema.definitions?.connectionRoute?.enum;
  const modes = schema.definitions?.deliveryMode?.enum;
  if (!Array.isArray(routes) || !Array.isArray(modes)
    || [routes, modes].some(values => !values.length || values.some(value => typeof value !== 'string')
      || new Set(values).size !== values.length)) throw new Error('Canonical route enums are missing or invalid');
  return '// Generated by npm run build from canonical agent-registration schemas.json. Do not edit.\n'
    + `export const connectionRouteOrder = ${JSON.stringify(routes)} as const;\n`
    + `export const deliveryModeOrder = ${JSON.stringify(modes)} as const;\n`;
}

/** Node build tooling only. The browser imports the emitted static function. */
export function generateRouteAvailabilityValidator() {
  const schema = JSON.parse(readFileSync(schemaFile, 'utf8'));
  const hash = createHash('sha256').update(JSON.stringify(schema)).digest('hex');
  const ajv = new Ajv({ strict: false, code: { source: true, esm: true } });
  addFormats(ajv);
  ajv.addSchema(schema);
  const validate = ajv.getSchema(schema.$id + '#/definitions/routeAvailability');
  if (!validate) throw new Error('Canonical routeAvailability schema is missing');
  return '// Generated by npm run build from canonical agent-registration schemas.json. Do not edit.\n'
    + '// Canonical schema SHA256: ' + hash + '\n'
    + standaloneCode(ajv, validate) + '\n';
}

export function routeAvailabilityValidatorPlugin() {
  return {
    name: 'canonical-route-availability-validator',
    buildStart() {
      const generated = generateRouteAvailabilityValidator();
      const previous = existsSync(validatorFile) ? readFileSync(validatorFile, 'utf8').replace(/\r\n/g, '\n') : '';
      if (previous !== generated) writeFileSync(validatorFile, generated);
      const enums = generateRouteAvailabilityEnums();
      const previousEnums = existsSync(routeEnumsFile) ? readFileSync(routeEnumsFile, 'utf8').replace(/\r\n/g, '\n') : '';
      if (previousEnums !== enums) writeFileSync(routeEnumsFile, enums);
    }
  };
}
