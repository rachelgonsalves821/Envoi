import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import Ajv from 'ajv';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';

const schemaFile = new URL('../../test/contract-fixtures/agent-registration/schemas.json', import.meta.url);
export const routeEnumsFile = new URL('../src/onboarding/route-enums.mjs', import.meta.url);
export const validatorFile = new URL('../src/onboarding/route-availability.validator.mjs', import.meta.url);

/** Node build tooling only. The browser imports the emitted static function. */
export function generateRouteAvailabilityValidator() {
  const schema = JSON.parse(readFileSync(schemaFile, 'utf8'));
  const hash = createHash('sha256').update(JSON.stringify(schema)).digest('hex');
  const ajv = new Ajv({ strict: false, code: { source: true, esm: true } });
  addFormats(ajv);
  ajv.addSchema(schema);
  const validate = ajv.getSchema(schema.$id + '#/definitions/routeAvailability');
  if (!validate) throw new Error('Canonical routeAvailability schema is missing');
  return '// Generated by npm run build from canonical agent-registration schemas.json. Do not edit.\n'
    + '// Canonical schema SHA256: ' + hash + '\n'
    + standaloneCode(ajv, validate) + '\n';
}

/** Emit only the browser's two enum lists; unrelated schema definitions stay in Node. */
export function generateRouteEnums(schema = JSON.parse(readFileSync(schemaFile, 'utf8'))) {
  const enums = ['connectionRoute', 'deliveryMode'].map(name => {
    const values = schema.definitions?.[name]?.enum;
    if (!Array.isArray(values) || !values.length || values.some(value => typeof value !== 'string')) {
      throw new Error('Canonical ' + name + ' enum is missing or invalid');
    }
    return JSON.stringify(values);
  });
  return '// Generated by npm run build from canonical agent-registration enums. Do not edit.\n'
    + 'export const connectionRoutes = Object.freeze(' + enums[0] + ');\n'
    + 'export const deliveryModes = Object.freeze(' + enums[1] + ');\n';
}

export function routeAvailabilityValidatorPlugin() {
  return {
    name: 'canonical-route-availability-validator',
    buildStart() {
      for (const [file, generated] of [
        [validatorFile, generateRouteAvailabilityValidator()],
        [routeEnumsFile, generateRouteEnums()]
      ] as const) {
        const previous = existsSync(file) ? readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : '';
        if (previous !== generated) writeFileSync(file, generated);
      }
    }
  };
}
